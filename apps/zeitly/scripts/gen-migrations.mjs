// Bundles src/db/migrations/*.sql into src/db/migrations/index.ts (so Next.js standalone builds carry the SQL).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const dir = new URL('../src/db/migrations/', import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((f) => `  { name: ${JSON.stringify(f.replace(/\.sql$/, ''))}, sql: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))} },`);
writeFileSync(join(dir, 'index.ts'), `// AUTO-GENERATED by scripts/gen-migrations.mjs – do not edit.\nexport const MIGRATIONS: Array<{ name: string; sql: string }> = [\n${entries.join('\n')}\n];\n`);
console.log('migrations bundled:', files.join(', '));
